-- description: Mark inventory counterparts among minifigures

-- Секция Counterpart инвентаря BrickLink встречается не только у деталей,
-- но и у фигурок. У 21108-1 рядом с gb001..gb004 стоят gb001i..gb004i:
-- те же фигурки без рюкзаков-протонников, собранные из деталей, которые
-- уже посчитаны в основной четвёрке. Это не пятая, шестая и так далее
-- фигурка набора, а другой взгляд на те же самые.
--
-- Без этой колонки набор показывал восемь фигурок вместо четырёх, а их
-- детали ложились в коллекцию вторым экземпляром. У деталей колонка
-- появилась в миграции 0028, у фигурок — здесь, по той же причине.
ALTER TABLE "bricktracker_minifigures"
ADD COLUMN "counterpart" BOOLEAN NOT NULL DEFAULT 0;
